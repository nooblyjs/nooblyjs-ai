test('step 1: the container view is code; Edit as code, change a label, save, and the diagram updates', async () => {
  const t = await startApp({ seed: true });
  try {
    const d = await t.get(`${API}/architecture/PRD-031/diagram`, { as: 'thabo-n' });
    assert.equal(d.etag, '"PRD-031.diagram@2"');
    assert.deepEqual(d.json.nodes.filter((n) => n.status === 'new').map((n) => n.label), ['Slot API', 'Slot cache']);
    assert.ok(d.json.edges.some((e) => e.from === 'gateway' && e.to === 'slotApi' && e.label === 'gRPC'));
    assert.match(d.json.provenance.text, /^Generated by Rhea Voss \(Architect agent\)/);

    const code = d.json.code.replace('"Slot API"', '"Slot service"');
    const saved = await t.put(`${API}/architecture/PRD-031/diagram`, { as: 'thabo-n', headers: { 'if-match': d.etag }, body: { code, changeNote: 'Renamed the Slot API' } });
    assert.equal(saved.status, 200);
    assert.equal(saved.etag, '"PRD-031.diagram@3"');
    assert.ok(saved.json.nodes.some((n) => n.id === 'slotApi' && n.label === 'Slot service'));
    assert.equal(t.eventLog.at(-1).type, 'architecture.diagram_updated');

    const stale = await t.put(`${API}/architecture/PRD-031/diagram`, { as: 'thabo-n', headers: { 'if-match': d.etag }, body: { code } });
    assert.equal(stale.status, 409);
  } finally {
    await t.close();
  }
});

