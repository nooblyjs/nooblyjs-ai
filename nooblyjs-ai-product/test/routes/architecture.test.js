    await t.post(`${API}/architecture/PRD-025/drafts`, { as: 'thabo-n', body: { kind: 'adr' } });
    await t.hosted.idle();
    const adrs = (await t.get(`${API}/architecture/PRD-025/adrs`, { as: 'thabo-n' })).json.adrs;
